// Writes supabase/functions/ask-operator/flexwash_catalog.ts, the FlexWash catalog
// bundled with Operator AI, from FlexWash's published partner API docs.
//
//   node scripts/gen-flexwash-catalog.mjs
//
// The live catalog doesn't need this: flexwash-catalog-sync refreshes it every day
// into the flexwash_catalog table, which ask-operator reads first. The bundled copy
// is the fallback for when that table is empty, so rerun this now and then to keep
// it close. The rules (read endpoints only, scopes) live in
// supabase/functions/_shared/flexwash_catalog_build.ts, shared with the sync.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { FLEX_DOCS_URL, buildFlexCatalog, parseDocs } from '../supabase/functions/_shared/flexwash_catalog_build.ts'

const here = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(here, '..', 'supabase', 'functions', 'ask-operator', 'flexwash_catalog.ts')

const { endpoints, held } = buildFlexCatalog(parseDocs(await (await fetch(FLEX_DOCS_URL)).text()))
const names = Object.keys(endpoints)
const header = `// GENERATED by scripts/gen-flexwash-catalog.mjs from ${FLEX_DOCS_URL.replace('swagger-ui-init.js', '')}
// on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand; rerun the script.
// ${names.length} read endpoints of the FlexWash partner API, for Operator AI. This is
// the fallback copy: the live list is the flexwash_catalog table (flexwash-catalog-sync).

import type { FlexEndpoint } from '../_shared/flexwash_catalog_build.ts'
export type { FlexEndpoint, FlexScope } from '../_shared/flexwash_catalog_build.ts'
`
writeFileSync(OUT, `${header}\nexport const FLEX_ENDPOINTS: Record<string, FlexEndpoint> = ${JSON.stringify(endpoints, null, 1)}\n`)
const count = {}
for (const e of Object.values(endpoints)) count[e.scope] = (count[e.scope] ?? 0) + 1
console.log(`Wrote ${names.length} endpoints to ${path.relative(process.cwd(), OUT)}`, count)
if (held.length) console.log('Held for review (not read-only by name):', held.map((h) => h.name).join(', '))
