-- 0096_invoice_vendors.sql
-- Master vendor list for Invoice Approval (per account). Seeded from Mighty
-- Wash's "Active Vendor Names" sheet. Powers the AI vendor match on inbound and
-- the editable vendor dropdown in the invoice modal.

create table if not exists public.invoice_vendors (
  id uuid primary key default gen_random_uuid(),
  account_id uuid not null references public.accounts(id) on delete cascade,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (account_id, name)
);
create index if not exists invoice_vendors_account_name on public.invoice_vendors (account_id, name);

alter table public.invoice_vendors enable row level security;
create policy invoice_vendors_select on public.invoice_vendors for select
  using (account_id = public.auth_account_id());
create policy invoice_vendors_insert on public.invoice_vendors for insert
  with check (account_id = public.auth_account_id() and public.auth_is_manager_plus());
create policy invoice_vendors_update on public.invoice_vendors for update
  using (account_id = public.auth_account_id() and public.auth_is_manager_plus());
create policy invoice_vendors_delete on public.invoice_vendors for delete
  using (account_id = public.auth_account_id() and public.auth_role() = 'owner');

