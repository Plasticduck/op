import { loadPdfLogo, placePdfLogo } from '@/lib/pdfLogo'
import { attendeesOf, fmtTime, type EventPayRow } from '@/lib/queries/eventPay'

// PDF for one Event Pay Request: event details, the team members with their
// times / hours / Mighty Maxx amount, totals and notes, with the Mighty Wash logo
// (public/mw-logo.png) top-right. Letter size, since it may be printed. jspdf +
// jspdf-autotable load on demand.

const ACCENT: [number, number, number] = [37, 99, 235]
const GRAY = 110
const money = (n: number) => `$${n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
const fileSafe = (s: string) => s.replace(/[^a-z0-9]+/gi, '-').replace(/^-+|-+$/g, '').toLowerCase()
export const fmtEventDate = (d: string) =>
  new Date(d + 'T12:00:00').toLocaleDateString('en-US', { weekday: 'short', month: 'short', day: 'numeric', year: 'numeric' })
const fmtStamp = (iso: string) =>
  new Date(iso).toLocaleString('en-US', { month: 'short', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit' })

type Doc = import('jspdf').jsPDF & { lastAutoTable?: { finalY: number } }

async function buildEventPayPdf(r: EventPayRow): Promise<Doc> {
  const { jsPDF } = await import('jspdf')
  const autoTable = (await import('jspdf-autotable')).default
  // ~400px is plenty for a 26mm-tall logo, and keeps the emailed PDF small.
  const logo = await loadPdfLogo('/mw-logo.png', { maxPx: 400 })

  const doc = new jsPDF({ format: 'letter', compress: true }) as Doc
  const pageW = doc.internal.pageSize.getWidth()
  placePdfLogo(doc, logo, { height: 26, y: 10 })

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.setTextColor(20)
  doc.text('Event Pay Request', 14, 19)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.setTextColor(GRAY)
  doc.text('Mighty Wash', 14, 25)
  doc.text(`Request ${r.id.slice(0, 8).toUpperCase()}  ·  Submitted ${fmtStamp(r.created_at)}`, 14, 30)
  doc.setDrawColor(...ACCENT)
  doc.setLineWidth(0.6)
  doc.line(14, 39, pageW - 14, 39)

  // Event details.
  autoTable(doc, {
    startY: 43,
    theme: 'plain',
    styles: { fontSize: 10, cellPadding: { top: 1.6, bottom: 1.6, left: 0, right: 4 } },
    columnStyles: { 0: { cellWidth: 34, textColor: GRAY }, 1: { fontStyle: 'bold', textColor: 20 } },
    margin: { left: 14, right: 14 },
    body: [
      ['Site', r.location?.name ?? 'Not specified'],
      ['Event', r.event_name],
      ['Event date', fmtEventDate(r.event_date)],
      ['Requested by', r.requester_name],
      ...(r.submitter_name && r.submitter_name !== r.requester_name ? [['Submitted by', r.submitter_name]] : []),
    ],
  })

  // Team members.
  const people = attendeesOf(r)
  const totalHours = people.reduce((a, p) => a + (Number(p.hours) || 0), 0)
  const maxx = people.filter((p) => p.mighty_maxx)
  const maxxTotal = maxx.reduce((a, p) => a + (Number(p.amount) || 0), 0)
  const right = { halign: 'right' as const }
  autoTable(doc, {
    startY: (doc.lastAutoTable?.finalY ?? 60) + 6,
    styles: { fontSize: 10, cellPadding: 2.4 },
    headStyles: { fillColor: ACCENT, fontStyle: 'bold' },
    footStyles: { fillColor: [237, 240, 245], textColor: 20, fontStyle: 'bold' },
    margin: { left: 14, right: 14 },
    head: [['Team member', 'Arrival', 'Departure', { content: 'Hours', styles: right }, 'Mighty Maxx', { content: 'Pay', styles: right }]],
    body: people.map((p) => [
      p.name,
      fmtTime(p.arrival),
      fmtTime(p.departure),
      { content: (Number(p.hours) || 0).toFixed(2), styles: right },
      p.mighty_maxx ? 'Yes' : 'No',
      { content: p.mighty_maxx ? money(Number(p.amount) || 0) : 'Hourly rate', styles: right },
    ]),
    foot: [[
      `Total (${people.length} team member${people.length === 1 ? '' : 's'})`,
      '',
      '',
      { content: totalHours.toFixed(2), styles: right },
      maxx.length ? `${maxx.length} Mighty Maxx` : '',
      { content: maxx.length ? money(maxxTotal) : '', styles: right },
    ]],
    showFoot: 'lastPage',
  })

  let y = (doc.lastAutoTable?.finalY ?? 100) + 8
  doc.setFontSize(9)
  doc.setTextColor(GRAY)
  doc.text('Mighty Maxx is paid the flat amount shown. Every other team member is paid their hourly rate for the hours shown.', 14, y, { maxWidth: pageW - 28 })
  y += 10

  if (r.notes?.trim()) {
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(10)
    doc.setTextColor(20)
    doc.text('Notes', 14, y)
    doc.setFont('helvetica', 'normal')
    const lines = doc.splitTextToSize(r.notes.trim(), pageW - 28) as string[]
    doc.text(lines, 14, y + 5.5)
  }

  const pageH = doc.internal.pageSize.getHeight()
  doc.setFontSize(8)
  doc.setTextColor(150)
  doc.text(`Generated by Operator on ${new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}`, 14, pageH - 10)
  return doc
}

const fileName = (r: EventPayRow) => `event-pay-${fileSafe(r.event_name) || 'event'}-${r.event_date}.pdf`

export async function downloadEventPayPdf(r: EventPayRow): Promise<void> {
  const doc = await buildEventPayPdf(r)
  doc.save(fileName(r))
}

// The PDF as base64 (no data: prefix), for attaching to the approval email.
export async function eventPayPdfBase64(r: EventPayRow): Promise<string> {
  const doc = await buildEventPayPdf(r)
  return String(doc.output('datauristring')).split(',')[1] ?? ''
}
